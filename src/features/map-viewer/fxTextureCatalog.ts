const specialFxTextureNames = new Map<number, string>([
  [-8, 'FX_BACK_ALPHA_CLUT'],
  [-7, 'FX_RAW_FRONT_BUFFER'],
  [-6, 'FX_RAW_BACK_BUFFER'],
  [-5, 'FX_RAW_Z_BUFFER'],
  [-4, 'FX_BACK_BUFFER_RECOPY64'],
  [-3, 'FX_BACK_BUFFER_COPY64'],
  [-2, 'FX_BACK_BUFFER_RECOPY'],
  [-1, 'FX_BACK_BUFFER_COPY']
]);

type FxTextureNameEnum = { [index: number]: string };

const fxTextureNamesByGame = new Map<string, FxTextureNameEnum>([
  ['DL', DlFxTextureNames],
  ['UYA', UyaFxTextureNames]
]);

export function fxTextureName(game: unknown, index: number): string {
  const gameFxTextureNames = typeof game === 'string'
    ? fxTextureNamesByGame.get(game.toUpperCase())
    : undefined;
  return specialFxTextureNames.get(index) ?? gameFxTextureNames?.[index] ?? `FX_TEXTURE_${index}`;
}
